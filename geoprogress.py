b = int(input("Введите первый элемент геометрической прогрессии" )) #первый элемент геометрической прогрессии 
q = int(input("Ввдеитемножитель геометрической прогрессии")) #множитель геометрической прогрессии
n = int(input("Введиете номер последнего элемента геометрической прогрессии")) #номер последнего элемента геометрической прогрессии
S = b * ((q**n) - 1) /(q-1)  #сумма геометрической прогрессии 
print(f"Cумма геометрической прогрессии: {S}") #вывод суммы геометрической прогрессии 